// Readiness scorecard. Usage: node evaluation/scorecard.mjs
// Reads the committed result files and writes evaluation/results/readiness-scorecard.md.
// Anything that has not been measured says "Not measured". Nothing here is estimated.
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const here=dirname(fileURLToPath(import.meta.url));
const R=(f)=>JSON.parse(readFileSync(resolve(here,'results',f),'utf8'));
const pct=(x)=>x==null?'n/a':(x*100).toFixed(1)+'%';
const b=R('benchmark-summary.json'),ho=b.heldout.engine,all=b.overall.engine;
const fresh=[['fresh-unseen (written by us, locked before the run)','decisions-fresh.json'],['fresh-unseen-3 (written by us, locked before the fixes)','decisions-fresh-3.json']].filter(([,f])=>existsSync(resolve(here,'results',f))).map(([n,f])=>{const r=R(f);return {n,correct:r.correct,total:r.n,acc:r.accuracy,missedToIgnore:r.wrong.filter(w=>w.decided==='IGNORE'&&w.expected!=='IGNORE').length,falseAlarm:r.wrong.filter(w=>w.expected==='IGNORE'&&w.decided!=='IGNORE').length};});
const aud=existsSync(resolve(here,'results/audience-summary.json'))?R('audience-summary.json'):null;
const lines=[
'# Load Bear readiness scorecard','',
'Generated by `node evaluation/scorecard.mjs`. **Every dataset here was written or labelled by the Load Bear team; none is independent evidence.** Real-email results are small and were partly used to fix the rules, so they are not reported as scores here.','',
'## The five measures','',
'| Measure | Result | Where it comes from |','|---|---|---|',
`| Responsibility detection (recall) | ${pct(ho.recall.value)} held-out, ${pct(all.recall.value)} overall (n=${ho.recall.n}/${all.recall.n}) | Extraction benchmark, ${b.scenarioCount} synthetic scenarios |`,
`| Inference accuracy (precision) | ${pct(ho.precision.value)} held-out, ${pct(all.precision.value)} overall | Same benchmark |`,
'| Planning accuracy | **Not measured** | Plans are validated by tests, but there is no labelled dataset of plans |',
'| Autonomous completion | **Not measured** | Bear does not complete tasks on its own yet (execution layer not built) |',
'| User burden (questions and corrections per email) | **Not measured** | Needs real use. The "Is that right?" buttons record it once `BEAR_DECISIONS_ENABLED=on` |','',
'## Decisions (ACT / ASK / WAIT / UPDATE / CLOSE / IGNORE)','',
'| Test set | Correct | Missed (said ignore when something was needed) | False alarms |','|---|---|---|---|',
...fresh.map(f=>`| ${f.n} | ${f.correct}/${f.total} (${pct(f.acc)}) | ${f.missedToIgnore} | ${f.falseAlarm} |`),'',
'The rules were fixed after each of these runs, so each set stopped being a fair test the moment it was used. Only the first run of each set counts.','',
...(aud?['## Synthetic audience (12 invented households, 480 emails)','',
'| Measure | Result |','|---|---|',
`| Exact decision | ${pct(aud.overall.exactDecision)} |`,
`| Responsibilities caught (recall) | ${pct(aud.overall.detectionRecall)} of ${aud.overall.needing} |`,
`| False alarms (said something when nothing was needed) | ${pct(aud.overall.falseAlarmRate)} of ${aud.overall.ignoring} |`,
`| Questions asked per 100 emails | ${aud.overall.questionsPer100} (of which sensitive offers, asked every time by design: ${aud.overall.sensitiveQuestionsPer100}) |`,
`| Missed deadlines | ${aud.overall.missedDeadlines} of ${aud.overall.deadlineEmails} emails with a deadline |`,
`| Fabricated dates | ${aud.overall.fabricatedDates} |`,'',
'Templates and rules were written by the same team, so this is optimistic. It is useful for relevance, user burden and as a repeatable harness. It already found one real bug: a bill ("payment of $X is due") was read as a receipt.','',]:[]),
'## Safety measures','',
'| Measure | Result |','|---|---|',
`| Fabricated deadlines (extraction benchmark) | ${all.fabricatedDeadlines} of ${b.scenarioCount} scenarios |`,
'| Missed deadlines on real emails | **Not measured at scale.** Small samples only; see the commit history for each batch |',
'| Unauthorised actions | Bear takes no external actions (no sending, paying or booking). This is a design rule, not a measurement |',
'| Incorrect actions | **Not measured** |','',
'## Headline measure for Load Bear','',
'Not "tasks completed without the user". Load Bear\'s job is to catch what a person would forget without nagging them. The proposed headline is:',
'**real responsibilities Bear missed, subject to a low number of questions per email.**','',
'## Is it ready?','',
'**No, not to act on its own.** It is reasonable as a suggestion the person confirms (that is how the Outlook panel uses it). Before it acts for people, it needs: at least 100 real, independently labelled emails; a pre-agreed miss rate and false-alarm rate; and the user-burden numbers from real use.',
''];
writeFileSync(resolve(here,'results/readiness-scorecard.md'),lines.join('\n'));
console.log(lines.join('\n'));
